import { existsSync, readFileSync } from "node:fs";
import { registerHooks } from "node:module";
import { extname } from "node:path";

const prismaSource = new URL("../", import.meta.url).href;
const generatedMarker = "/* !!! This is code generated by Prisma. Do not edit directly. !!! */";
const isGenerated = (url) =>
  /\/(?:client|browser|enums|models|internal\/(?:class|prismaNamespace|prismaNamespaceBrowser))\.ts$/.test(
    url.pathname
  ) &&
  existsSync(url) &&
  readFileSync(url, "utf8").trimStart().startsWith(generatedMarker);
const isCompiler = (url) => {
  if (!url.endsWith("/internal/query_compiler_bg.wasm?module")) return false;
  const parent = new URL("./class.ts", url);
  return (
    isGenerated(parent) &&
    readFileSync(parent, "utf8").includes('"@prisma/client/runtime/wasm-compiler-edge"')
  );
};

// Keep source suffix resolution inside Prisma; generated clients may use custom output directories.
registerHooks({
  resolve(specifier, context, nextResolve) {
    if (
      specifier === "./query_compiler_bg.wasm?module" &&
      context.parentURL?.endsWith("/internal/class.ts") &&
      isCompiler(new URL(specifier, context.parentURL).href)
    ) {
      return { url: new URL(specifier, context.parentURL).href, shortCircuit: true };
    }
    try {
      return nextResolve(specifier, context);
    } catch (error) {
      if (
        !context.parentURL?.match(/\.[cm]?ts$/) ||
        !specifier.startsWith(".") ||
        extname(specifier) ||
        !(error instanceof Error) ||
        !("code" in error) ||
        typeof error.code !== "string" ||
        !["ERR_MODULE_NOT_FOUND", "ERR_UNSUPPORTED_DIR_IMPORT"].includes(error.code)
      ) {
        throw error;
      }
      for (const suffix of [".ts", "/index.ts"]) {
        const candidate = new URL(specifier + suffix, context.parentURL);
        if (
          existsSync(candidate) &&
          (isGenerated(candidate) ||
            (context.parentURL.startsWith(prismaSource) && candidate.href.startsWith(prismaSource)))
        )
          return nextResolve(candidate.href, context);
      }
      throw error;
    }
  },
  load(url, context, nextLoad) {
    if (!isCompiler(url)) return nextLoad(url, context);
    const asset = new URL(url);
    asset.search = "";
    return {
      format: "module",
      shortCircuit: true,
      source: `import { readFileSync } from "node:fs";
export default new WebAssembly.Module(readFileSync(new URL(${JSON.stringify(asset.href)})));`,
    };
  },
});
